    if (lang === 'English') return originalText.get(arguments.calleeNode) || raw;
    const lead = (raw.match(/^\\s*/) || [''])[0], trail = (raw.match(/\\s*$/) || [''])[0];
    const n = norm(raw); if (!n) return raw;
    const map = maps[lang] || {};
